/**
 * Sidebar - Main navigation sidebar component
 */
function Sidebar({ role = 'ADMIN', isOpen = false, onClose }) {
  const { user, logout } = useAuth();

  const getNavItems = () => {
    switch (role) {
      case 'FACULTY': return facultyNavItems;
      case 'STUDENT': return studentNavItems;
      default: return adminNavItems;
    }
  };

  const navItems = getNavItems();

  const handleLogout = () => {
    if (onClose) onClose();
    logout();
    window.location.href = '/login';
  };

  const handleNavClick = () => {
    // Always close sidebar when selecting a nav item.
    if (onClose) {
      onClose();
    }
  };

  const userRole = role || 'ADMIN';
  const getInitials = (name) => {
    if (!name) return 'U';
    return name.split(' ').map(n => n[0]).join('').toUpperCase().slice(0, 2);
  };

  return (
    <>
      <aside className={`sidebar ${isOpen ? 'open' : 'closed'}`}>
        <div className="sidebar-header">
          <div className="sidebar-logo">
            <LogoIcon />
            <h1>CampusOne</h1>
          </div>
          <button className="sidebar-close-btn" onClick={onClose} aria-label="Close menu">
            <CloseIcon />
          </button>
        </div>
        <nav className="sidebar-nav">
          {navItems.map((item) => (
            <NavLink
              key={item.path}
              to={item.path}
              className={({ isActive }) => `nav-item ${isActive ? 'active' : ''}`}
              end={item.path === `/${userRole.toLowerCase()}/dashboard`}
              onClick={handleNavClick}
            >
              {item.icon}
              <span>{item.label}</span>
            </NavLink>
          ))}
        </nav>
        <div className="sidebar-user">
          <div className="user-info">
            <div className="user-avatar">{getInitials(user?.name || 'User')}</div>
            <div className="user-details">
              <div className="user-name">{user?.name || 'User'}</div>
              <div className="user-role">{userRole}</div>
            </div>
          </div>
          <button className="logout-btn" onClick={handleLogout}>
            <LogoutIcon />
            <span>Logout</span>
          </button>
        </div>
      </aside>
    </>
  );
}

export default Sidebar;

